// ─── Listening Prayer (Hearing God) ────────────────────────────
// Most Christians pray. Far fewer have learned to listen. Yet the Bible
// is, end to end, the story of a God who speaks — and of His people learning
// to recognize His voice. This guide is non-charismatic-vs-cessationist
// neutral: every Christian tradition agrees God speaks through Scripture
// and that the Spirit illumines the believer (1 Cor 2:12-13). What that
// looks like in practice is what most apps refuse to teach.

